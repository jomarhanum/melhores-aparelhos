const fichaBancada = (p: BancadaDados): [string, string][] => [
  ['Capacidade', `${p.litros} litros`],
  ['Voltagem', p.voltagem],
  ...(p.potencia ? [['Potência', p.potencia] as [string, string]] : []),
  ...(p.temperatura ? [['Temperatura', p.temperatura] as [string, string]] : []),
  ...(p.timer ? [['Timer', p.timer] as [string, string]] : []),
  ['Convecção', p.conveccao],
  ['Funções', p.funcoes],
  ...(p.porta ? [['Porta e acabamento', p.porta] as [string, string]] : []),
  ...(p.medidas ? [['Medidas', p.medidas] as [string, string]] : []),
  ...(p.peso ? [['Peso', p.peso] as [string, string]] : []),
  ...(p.garantia ? [['Garantia', p.garantia] as [string, string]] : []),
];

